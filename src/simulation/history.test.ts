import { describe, expect, it } from "vitest";
import { defaultConfig } from "@diagramwise/simulation-core";
import { parseEventRun } from "./history";
import type { EventRunArtifact } from "./protocol";

function artifact(): EventRunArtifact {
  return {
    contractVersion: "2", engineVersion: "event-v1", profileVersion: "profiles-v1",
    scope: { designId: "design", canvasId: "canvas", exerciseId: null },
    graphFingerprint: "fingerprint",
    topology: {
      nodes: [
        { id: "client", kind: "client", label: "Client", x: 0, y: 0, config: { ...defaultConfig("client") } },
        { id: "api", kind: "service", label: "API", x: 200, y: 0, config: { ...defaultConfig("service") } },
      ],
      edges: [{ id: "client-api", from: "client", to: "api", weight: 1 }],
    },
    workload: { rps: 100, pattern: "steady", seed: 1 },
    commands: [],
  };
}

describe("parseEventRun", () => {
  it.each([-1, 0x100000000])("rejects out-of-range seed %s before replay", seed => {
    const value = artifact();
    value.workload.seed = seed;
    expect(() => parseEventRun(value)).toThrow("invalid workload");
  });

  it("accepts cloud command timelines longer than one hour", () => {
    const value = artifact();
    value.commands = [{ atMs: 7_200_000, command: { type: "workload", rps: 50 } }];
    expect(parseEventRun(value).commands).toEqual(value.commands);
  });

  it("accepts a replay generated by the shared simulation model", () => {
    expect(parseEventRun(artifact())).toEqual(artifact());
  });

  it("rejects an imported replay with an unknown model before a worker starts", () => {
    const value = artifact();
    (value.topology.nodes[1] as { kind: string }).kind = "made-up-model";
    expect(() => parseEventRun(value)).toThrow("invalid model");
  });

  it("rejects zero-weight imported connections", () => {
    const value = artifact();
    value.topology.edges[0].weight = 0;
    expect(() => parseEventRun(value)).toThrow("positive weights");
  });
});
